package com.example.jaldrishti.ai

import android.util.Log
import com.example.jaldrishti.BuildConfig
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import org.json.JSONArray
import org.json.JSONObject
import java.util.concurrent.TimeUnit

/**
 * OpenAI Client - Handles text generation using OpenRouter API
 */
class OpenAIClient(
    private val apiKey: String = BuildConfig.OPENAI_API_KEY
) {
    private val client = OkHttpClient.Builder()
        .connectTimeout(30, TimeUnit.SECONDS)
        .readTimeout(60, TimeUnit.SECONDS)
        .writeTimeout(60, TimeUnit.SECONDS)
        .build()
    
    private val systemPrompt = """
        You are Krushi Mitra, an AI assistant for a Carbon Credit ecosystem app in India called Carbon Setu.
        
        Key Information:
        - Farmers register land by walking GPS boundaries using their phone
        - They earn money from carbon credits generated by their sustainable farming
        - Payment happens the following year after credit generation
        - Emergency fund available from interest on locked credits
        - Government approves all land registrations through blockchain
        - Companies can buy carbon credits to offset their emissions
        
        CRITICAL Language Rule:
        - ALWAYS reply STRICTLY in the same language the user is writing or the language explicitly requested
        - If Hindi is requested, reply ENTIRELY in Hindi using Devanagari script
        - If Marathi is requested, reply ENTIRELY in Marathi using Devanagari script
        - NEVER mix languages unless the user mixes them
        - Keep responses concise (2-3 sentences max)
        - Use simple farmer-friendly language
    """.trimIndent()
    
    suspend fun chat(message: String, language: String = "English"): String = withContext(Dispatchers.IO) {
        if (apiKey.isEmpty()) {
            Log.e("OpenAIClient", "API key is empty")
            return@withContext "Please add your OpenAI API key to gradle.properties"
        }
        
        val prompt = when (language) {
            "English" -> message
            "Hindi"   -> "तुम्हें हिंदी में जवाब देना है। प्रश्न: $message"
            "Marathi" -> "तुम्हाला मराठीत उत्तर द्यायचे आहे. प्रश्न: $message"
            else      -> "Please respond STRICTLY in $language language only. Question: $message"
        }
        
        try {
            val messages = JSONArray().apply {
                put(JSONObject().apply {
                    put("role", "system")
                    put("content", systemPrompt)
                })
                put(JSONObject().apply {
                    put("role", "user")
                    put("content", prompt)
                })
            }
            
            val json = JSONObject().apply {
                put("model", "openai/gpt-4o-mini")  // Cheap paid model (~$0.0002/req), works with OpenRouter credits
                put("messages", messages)
                put("max_tokens", 256)
                put("temperature", 0.7)
            }
            
            val requestBody = json.toString().toRequestBody("application/json".toMediaType())
            
            val request = Request.Builder()
                .url("https://openrouter.ai/api/v1/chat/completions")
                .addHeader("Authorization", "Bearer $apiKey")
                .addHeader("Content-Type", "application/json")
                .addHeader("HTTP-Referer", "https://github.com/your-repo") // Optional
                .addHeader("X-Title", "Carbon Credit Assistant") // Optional
                .post(requestBody)
                .build()
            
            Log.d("OpenAIClient", "Sending request to OpenAI API")
            
            val response = client.newCall(request).execute()
            
            if (response.isSuccessful) {
                val responseBody = response.body?.string() ?: return@withContext "No response from AI"
                val jsonResponse = JSONObject(responseBody)
                
                val choices = jsonResponse.optJSONArray("choices")
                if (choices != null && choices.length() > 0) {
                    val firstChoice = choices.getJSONObject(0)
                    val message = firstChoice.optJSONObject("message")
                    val aiResponse = message?.optString("content", "") ?: ""
                    
                    Log.d("OpenAIClient", "Response received: ${aiResponse.take(100)}...")
                    aiResponse.ifEmpty { "Sorry, I couldn't generate a response." }
                } else {
                    "Sorry, I couldn't generate a response."
                }
            } else {
                val errorBody = response.body?.string() ?: ""
                val error = "HTTP ${response.code}: ${response.message}"
                Log.e("OpenAIClient", "$error | Body: $errorBody")
                when (response.code) {
                    401 -> "AI Error: Invalid API key (401). Please check your OpenRouter key."
                    402 -> "AI Error: Insufficient credits (402). Please top up your OpenRouter account."
                    403 -> "AI Error: Access forbidden (403). Check your OpenRouter key permissions."
                    429 -> "AI Error: Rate limit exceeded (429). Please wait a moment and try again."
                    else -> "AI Error: $error. Please try again."
                }
            }
        } catch (e: Exception) {
            Log.e("OpenAIClient", "Connection error", e)
            "Connection error: ${e.message}. Please check your internet connection."
        }
    }
    
    suspend fun testConnection(): Boolean = withContext(Dispatchers.IO) {
        try {
            val request = Request.Builder()
                .url("https://openrouter.ai/api/v1/models")
                .addHeader("Authorization", "Bearer $apiKey")
                .get()
                .build()
            
            val response = client.newCall(request).execute()
            response.isSuccessful
        } catch (e: Exception) {
            Log.e("OpenAIClient", "Connection test failed", e)
            false
        }
    }
}